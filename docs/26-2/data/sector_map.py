def build():
    m = {}
    for sec, names in SECTORS.items():
        for n in names.split():
            n = n.replace('@', ' ')
            if n in m:
                raise ValueError(f'중복 분류: {n} ({m[n]} / {sec})')
            m[n] = sec
    return m


